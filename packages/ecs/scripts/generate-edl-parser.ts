import peggy from 'peggy';
import tspegjs from 'ts-pegjs';

const main = async (): Promise<void> => {
  const grammarPath = './src/edl/edl.peggy';
  const outPath = './src/edl/parser.ts';

  const file = Bun.file(grammarPath);

  const grammar = await file.text();

  const customHeader = [
    `/* This file is generated by scripts/generate-edl-parser.ts. Do not edit manually. */`,
    `import { toCamelCase } from 'odgn-helpers/string';`
  ].join('\n');

  const source = peggy.generate(grammar, {
    format: 'es',
    output: 'source',
    plugins: [tspegjs],
    tspegjs: {
      customHeader
    }
  }) as string;

  await Bun.write(outPath, source);

  console.log(`Generated: ${outPath}`);
};

try {
  await main();
} catch (error) {
  console.error(error);
  process.exit(1);
}
